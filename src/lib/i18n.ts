export function translateInterfaceText(value: string, locale: AppLocale) {
  if (locale === "en") return value;

  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const source = value.trim();
  if (!source) return value;

  const exact = translations[source] ?? sentenceTranslations[source];
  if (exact) return `${leading}${exact[locale]}${trailing}`;

  for (const entry of patterns) {
    const match = source.match(entry.pattern);
    if (match) return `${leading}${entry[locale](...match.slice(1))}${trailing}`;
  }

  return value;
}
